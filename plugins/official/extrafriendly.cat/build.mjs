import { realpath, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { DEFAULT_JOKE } from "./jokes.js";

// Reuse the desktop build toolchain. Resolve through the real Vite package path
// so this works with pnpm's isolated node_modules layout on Windows and macOS.
const viteManifest = await realpath(new URL("../../../apps/desktop/node_modules/vite/package.json", import.meta.url));
const require = createRequire(viteManifest);
const { build } = require("esbuild");
await build({
  entryPoints: [fileURLToPath(new URL("./companion.js", import.meta.url))],
  outfile: fileURLToPath(new URL("./index.js", import.meta.url)),
  bundle: true,
  platform: "browser",
  format: "esm",
  target: "chrome146",
  charset: "utf8",
  minify: false,
  logLevel: "warning",
  banner: { js: "// Generated by build.mjs from companion.js and the pure source modules. Do not edit by hand." },
});

// The installer copies only declared panel HTML, not its undeclared sidecars.
// Bundle our own script/style without changing the host's file or permission contracts.
const template = await readFile(new URL("./panel/template.html", import.meta.url), "utf8");
const styles = await readFile(new URL("./panel/style.css", import.meta.url), "utf8");
const script = await readFile(new URL("./panel/panel.js", import.meta.url), "utf8");
const hash = (text) => createHash("sha256").update(text).digest("base64");
const policy = `default-src 'none'; script-src 'sha256-${hash(script)}'; style-src 'sha256-${hash(styles)}'; img-src 'self'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`;
const panel = template
  .replace("{{INITIAL_JOKE}}", DEFAULT_JOKE)
  .replace(/content="default-src[^\"]+"/, `content="${policy}"`)
  .replace('<link rel="stylesheet" href="style.css">', `<style>${styles}</style>`)
  .replace(/^[ \t]*<script src="panel.js" defer><\/script>[ \t]*\r?\n/m, "")
  .replace("</body>", `<script>${script}</script>\n</body>`);
await writeFile(new URL("./panel/index.html", import.meta.url), panel);
