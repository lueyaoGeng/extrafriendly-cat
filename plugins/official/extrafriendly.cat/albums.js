const checkedAt = "2026-10-13";

function review(score, date, path, edition = "专辑乐评") {
  return {
    score,
    scale: 10,
    source: "Pitchfork",
    kind: "critic",
    date,
    checkedAt,
    edition,
    url: `https://pitchfork.com/reviews/albums/${path}/`,
  };
}

function album(record) {
  const query = `${record.artist} ${record.title}`;
  return {
    ...record,
    spotifyUrl: `https://open.spotify.com/search/${encodeURIComponent(query)}/albums`,
    neteaseUrl: `https://music.163.com/#/search/m/?s=${encodeURIComponent(query)}&type=10`,
    platformLinkKind: "search",
  };
}

